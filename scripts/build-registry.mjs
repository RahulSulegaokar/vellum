// Generates the Vellum source registry and the app theme from the files in this repo.
//
//   registry/themes/vellum.tokens.json  ->  app/theme.css  +  the "vellum-theme" registry item
//   components/ui/*.tsx                 ->  one registry:ui item each (deps derived from imports)
//   hooks/*.ts                          ->  one registry:hook item each
//
// Run with `npm run registry:generate`; then `npm run registry:build` writes public/r.
import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { basename, join } from "node:path"

const ROOT = new URL("..", import.meta.url).pathname
const OWNER_REPO = "RahulSulegaokar/vellum"
const THEME = "vellum-theme"
const at = (name) => `${OWNER_REPO}/${name}`

const tokens = JSON.parse(readFileSync(join(ROOT, "registry/themes/vellum.tokens.json"), "utf8"))

/* ---------------------------------- Theme ---------------------------------- */

const block = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n")}\n}\n`

writeFileSync(
  join(ROOT, "app/theme.css"),
  `/* Generated by scripts/build-registry.mjs from registry/themes/vellum.tokens.json. Do not edit by hand. */\n\n` +
    block("@theme inline", tokens.theme) +
    "\n" +
    block(":root", tokens.light) +
    "\n" +
    block(".dark", tokens.dark)
)

/* -------------------------------- Components -------------------------------- */

const pkgOf = (spec) => (spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0])
const IGNORE = new Set(["react", "react-dom", "next"])

function analyse(file) {
  const src = readFileSync(file, "utf8")
  const deps = new Set()
  const reg = new Set([at(THEME)])
  for (const [, spec] of src.matchAll(/from\s+"([^"]+)"/g)) {
    if (spec === "@/lib/utils") reg.add("utils")
    else if (spec.startsWith("@/components/ui/")) reg.add(at(basename(spec)))
    else if (spec.startsWith("@/hooks/")) reg.add(at(basename(spec)))
    else if (!spec.startsWith(".") && !spec.startsWith("@/")) {
      const p = pkgOf(spec)
      if (!IGNORE.has(p)) deps.add(p)
    }
  }
  return { deps: [...deps].sort(), reg: [...reg].sort() }
}

const title = (name) => name.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ")

const items = [
  {
    name: THEME,
    type: "registry:theme",
    title: "Vellum theme",
    description: "Vellum design tokens: colours, field and control tokens, shadows, radius scale (light and dark).",
    cssVars: { theme: tokens.theme, light: tokens.light, dark: tokens.dark },
  },
]

// Only hooks that a component actually imports are published (others are gallery-only helpers).
const usedHooks = new Set(
  readdirSync(join(ROOT, "components/ui"))
    .flatMap((f) => [...readFileSync(join(ROOT, "components/ui", f), "utf8").matchAll(/from\s+"@\/hooks\/([^"]+)"/g)].map((m) => `${m[1]}.ts`))
)
for (const f of readdirSync(join(ROOT, "hooks")).filter((f) => usedHooks.has(f)).sort()) {
  const name = f.replace(/\.ts$/, "")
  const { deps } = analyse(join(ROOT, "hooks", f))
  items.push({ name, type: "registry:hook", title: title(name), ...(deps.length && { dependencies: deps }), files: [{ path: `hooks/${f}`, type: "registry:hook" }] })
}

for (const f of readdirSync(join(ROOT, "components/ui")).filter((f) => f.endsWith(".tsx")).sort()) {
  const name = f.replace(/\.tsx$/, "")
  const { deps, reg } = analyse(join(ROOT, "components/ui", f))
  items.push({
    name,
    type: "registry:ui",
    title: title(name),
    ...(deps.length && { dependencies: deps }),
    registryDependencies: reg.filter((r) => r !== at(name)),
    files: [{ path: `components/ui/${f}`, type: "registry:ui" }],
  })
}

writeFileSync(
  join(ROOT, "registry.json"),
  JSON.stringify({ $schema: "https://ui.shadcn.com/schema/registry.json", name: "vellum", homepage: `https://github.com/${OWNER_REPO}`, items }, null, 2) + "\n"
)

console.log(`registry.json: ${items.length} items; app/theme.css written`)
